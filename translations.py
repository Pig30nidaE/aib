def translate(language, message, **values):
    return (KO.get(message, message) if language == "ko" else message).format(**values)


def translate_indicator(language, message):
    """Translate the existing rule text without changing the rules or their outputs."""
    patterns = [
        (r"Listing has (\d+) recorded spelling error\(s\)\.", "Listing has {count} recorded spelling error(s).", "count"),
        (r"Seller rating is ([\d.]+) / 5\.", "Seller rating is {rating} / 5.", "rating"),
        (r"Seller has (\d+) reviews\.", "Seller has {count} reviews.", "count"),
    ]
    for pattern, template, field in patterns:
        match = re.fullmatch(pattern, message)
        if match:
            return translate(language, template, **{field: match.group(1)})
    return translate(language, message)
